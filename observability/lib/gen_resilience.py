#!/usr/bin/env python3
"""Generate the retry alerts of architecture section 24.5 from policy/resilience/policy.yaml."""
import argparse
import sys
from pathlib import Path

import yaml

OBS = Path(__file__).resolve().parents[1]
POLICY = OBS.parent / "policy" / "resilience" / "policy.yaml"
OUT = OBS / "alerts" / "application" / "resilience.yaml"
RB = "https://github.com/whoisqen/payments-platform/blob/main/docs/runbooks/application"
DASH = "https://grafana.payments.internal/d/payments"
HEADER = "# Generated by observability/lib/gen_resilience.py from policy/resilience/policy.yaml; do not edit.\n"


def labels(severity, mode):
    return {"severity": severity, "team": "payments-core", "service": "resilience", "owner": "payments-core-oncall", "layer": "application", "failure_mode": f"application-{mode}"}


def build(policy):
    ratio = policy["defaults"]["retry_budget_ratio"]
    critical = sorted(n for n, d in policy["dependencies"].items() if d.get("budget_alert") == "critical")
    pattern = "|".join(critical)
    rules = [
        {
            "alert": "RetryStorm",
            "expr": f"sum by (dependency) (rate(retry_total[5m])) / sum by (dependency) (rate(dependency_requests_total[5m])) > {ratio:g}",
            "for": "5m",
            "labels": labels("warning", "retry-storm"),
            "annotations": {"summary": f"Retries exceed {ratio:.0%} of the traffic to a dependency", "runbook_url": f"{RB}/warnings.md#retry-storm", "dashboard_url": DASH},
        },
        {
            "alert": "RetryBudgetExhausted",
            "expr": f'sum by (dependency) (rate(retry_budget_exhausted_total{{dependency=~"{pattern}"}}[5m])) > 0',
            "for": "2m",
            "labels": labels("critical", "retry-budget-exhausted"),
            "annotations": {"summary": "The retry budget of the locker or PSP sync is exhausted", "runbook_url": f"{RB}/retry-budget-exhausted.md", "dashboard_url": DASH},
        },
        {
            "alert": "RetryBudgetExhaustedNonCritical",
            "expr": f'sum by (dependency) (rate(retry_budget_exhausted_total{{dependency!~"{pattern}"}}[5m])) > 0',
            "for": "10m",
            "labels": labels("warning", "retry-budget-exhausted-non-critical"),
            "annotations": {"summary": "The retry budget of a dependency is exhausted", "runbook_url": f"{RB}/warnings.md#retry-budget-exhausted-non-critical", "dashboard_url": DASH},
        },
    ]
    return {
        "apiVersion": "monitoring.coreos.com/v1",
        "kind": "PrometheusRule",
        "metadata": {"name": "alerts-application-resilience", "namespace": "monitoring", "labels": {"app.kubernetes.io/part-of": "payments-platform", "prometheus": "platform"}},
        "spec": {"groups": [{"name": "application-resilience", "rules": rules}]},
    }


def render():
    return HEADER + yaml.safe_dump(build(yaml.safe_load(POLICY.read_text())), sort_keys=False, width=10000)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            print("stale: " + str(OUT), file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
