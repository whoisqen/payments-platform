#!/usr/bin/env python3
"""Generate multi-window multi-burn-rate PrometheusRule files from Sloth prometheus/v1 SLO files."""
import argparse
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
OUT = HERE / "generated"
HEADER = "# Generated by observability/slo/generate.py from the Sloth file; do not edit.\n"
PERIOD_DAYS = 30
RECORD_WINDOWS = ["1m", "5m", "30m", "1h", "6h", "3d"]
# (suffix, burn rate, long window, short window, kind): table of section 7
WINDOWS = [
    ("BurnFast", 14.4, "1h", "5m", "page"),
    ("BurnSlow", 6.0, "6h", "30m", "page"),
    ("BurnTicket", 1.0, "3d", "6h", "ticket"),
]
# Only a 99.99% budget (4.3 min per 30 days) needs the extra fastest window
FASTEST = ("BurnFastest", 50.0, "5m", "1m", "page")
FASTEST_MIN_OBJECTIVE = 99.99
SUMMARY_SUFFIX = {
    "BurnFastest": "50x over 5m/1m",
    "BurnFast": "14.4x over 1h/5m",
    "BurnSlow": "6x over 6h/30m",
    "BurnTicket": "1x over 3d/6h",
}


def fmt(number):
    return f"{number:.10g}"


def windows_for(objective):
    wins = list(WINDOWS)
    if objective >= FASTEST_MIN_OBJECTIVE:
        wins.insert(0, FASTEST)
    return wins


def failure_mode(slo_spec):
    base = slo_spec["alerting"]["annotations"]["runbook_url"].rsplit("/", 1)[-1][:-3]
    return f"application-slo-{base}"


def build(doc):
    service = doc["service"]
    base_labels = dict(doc.get("labels", {}))
    groups = []
    for slo in doc["slos"]:
        sid = f"{service}-{slo['name']}"
        ident = {"sloth_id": sid, "sloth_service": service, "sloth_slo": slo["name"]}
        sel = ",".join(f'{k}="{v}"' for k, v in ident.items())
        objective = float(slo["objective"])
        budget = fmt(1 - objective / 100)
        events = slo["sli"]["events"]
        rec_labels = {**ident, **base_labels}

        sli_rules = []
        for win in RECORD_WINDOWS:
            err = events["error_query"].replace("{{.window}}", win)
            tot = events["total_query"].replace("{{.window}}", win)
            sli_rules.append({"record": f"slo:sli_error:ratio_rate{win}", "expr": f"({err}) / ({tot})", "labels": dict(rec_labels)})
        sli_rules.append({
            "record": f"slo:sli_error:ratio_rate{PERIOD_DAYS}d",
            "expr": f"sum_over_time(slo:sli_error:ratio_rate5m{{{sel}}}[{PERIOD_DAYS}d]) / count_over_time(slo:sli_error:ratio_rate5m{{{sel}}}[{PERIOD_DAYS}d])",
            "labels": dict(rec_labels),
        })
        join = "/ on(sloth_id, sloth_slo, sloth_service) group_left()"
        meta_rules = [
            {"record": "slo:objective:ratio", "expr": f"vector({fmt(objective / 100)})", "labels": dict(rec_labels)},
            {"record": "slo:error_budget:ratio", "expr": f"vector(1-{fmt(objective / 100)})", "labels": dict(rec_labels)},
            {"record": "slo:time_period:days", "expr": f"vector({PERIOD_DAYS})", "labels": dict(rec_labels)},
            {"record": "slo:current_burn_rate:ratio", "expr": f"slo:sli_error:ratio_rate5m{{{sel}}} {join} slo:error_budget:ratio{{{sel}}}", "labels": dict(rec_labels)},
            {"record": "slo:period_burn_rate:ratio", "expr": f"slo:sli_error:ratio_rate{PERIOD_DAYS}d{{{sel}}} {join} slo:error_budget:ratio{{{sel}}}", "labels": dict(rec_labels)},
            {"record": "slo:period_error_budget_remaining:ratio", "expr": f"1 - slo:period_burn_rate:ratio{{{sel}}}", "labels": dict(rec_labels)},
        ]

        alerting = slo["alerting"]
        alert_rules = []
        for suffix, burn, long_w, short_w, kind in windows_for(objective):
            threshold = f"({fmt(burn)} * {budget})"
            sev = alerting[f"{kind}_alert"]["labels"]
            alert_rules.append({
                "alert": alerting["name"] + suffix,
                "expr": f"slo:sli_error:ratio_rate{long_w}{{{sel}}} > {threshold} and slo:sli_error:ratio_rate{short_w}{{{sel}}} > {threshold}",
                "labels": {**base_labels, **alerting.get("labels", {}), **sev, "failure_mode": failure_mode(slo), "layer": "application", "slo": sid},
                "annotations": {**alerting["annotations"], "summary": f"{alerting['annotations']['summary']} ({SUMMARY_SUFFIX[suffix]})"},
            })
        groups += [
            {"name": f"slo-sli-recordings-{sid}", "rules": sli_rules},
            {"name": f"slo-meta-recordings-{sid}", "rules": meta_rules},
            {"name": f"slo-alerts-{sid}", "rules": alert_rules},
        ]
    return {
        "apiVersion": "monitoring.coreos.com/v1",
        "kind": "PrometheusRule",
        "metadata": {"name": f"slo-{service}", "namespace": "monitoring", "labels": {"app.kubernetes.io/part-of": "payments-platform", "prometheus": "platform"}},
        "spec": {"groups": groups},
    }


def render(doc):
    return HEADER + yaml.safe_dump(build(doc), sort_keys=False, width=10000)


def sources():
    return sorted(HERE.glob("*.yaml"))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="fail when generated files differ from the committed ones")
    args = ap.parse_args(argv)
    OUT.mkdir(exist_ok=True)
    stale = []
    for src in sources():
        doc = yaml.safe_load(src.read_text())
        target = OUT / f"{doc['service']}.yaml"
        text = render(doc)
        if args.check:
            if not target.exists() or target.read_text() != text:
                stale.append(target.name)
        else:
            target.write_text(text)
    if stale:
        print("stale generated files: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
