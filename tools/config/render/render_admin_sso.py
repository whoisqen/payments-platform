#!/usr/bin/env python3
"""Write the Okta sign-in of Argo CD, Vault and Sentry from config/platform.yaml (access.*, dns.admin_zone, naming.prefix).

Usage: render_admin_sso.py [--check]. Without --check the files are rewritten; with it the exit code is 1 when any file would change.
Files:
  deploy/platform/argocd/values.yaml        whole values file of the Argo CD add-on: OIDC login, RBAC by group, client ExternalSecret
  deploy/platform/vault/oidc/               admin.hcl, readonly.hcl, configure-oidc.sh: run by an operator, no workload holds the client secret
  deploy/platform/sentry/manifests/externalsecret-oidc.yaml, deploy/platform/sentry/oidc-values.yaml: OIDC client of Sentry
The Okta applications and the secrets <prefix>/shared-services/<tool>/oidc come from infra/modules/okta-sso.
"""
import stat
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "deploy" / "platform"
CENTRAL_ENV = "shared-services"

# Role of each group of access.grafana_groups in Argo CD and in Vault; a group that is not listed (finance) gets nothing.
# The administrator group is the only one that changes anything; the rest read.
ARGOCD_ROLE = {"admin": "role:admin", "sre": "role:readonly", "security": "role:readonly", "engineering": "role:readonly", "audit": "role:readonly"}
VAULT_POLICY = {"admin": "admin", "sre": "readonly", "security": "readonly", "engineering": "readonly", "audit": "readonly"}

ADMIN_HCL = """# Vault policy of the administrators of the identity provider group: manages Vault itself, reads no secret.
# Generated by tools/config/render/render_admin_sso.py; edit the generator, not this file.
path "sys/*" {
  capabilities = ["create", "read", "update", "delete", "list", "sudo"]
}
path "auth/*" {
  capabilities = ["create", "read", "update", "delete", "list", "sudo"]
}
path "identity/*" {
  capabilities = ["create", "read", "update", "delete", "list"]
}
# No administrator reads or changes the stored secrets; sys/raw would bypass this
path "secret/data/*" {
  capabilities = ["deny"]
}
path "secret/delete/*" {
  capabilities = ["deny"]
}
path "secret/undelete/*" {
  capabilities = ["deny"]
}
path "secret/destroy/*" {
  capabilities = ["deny"]
}
path "sys/raw/*" {
  capabilities = ["deny"]
}
"""

READONLY_HCL = """# Vault policy of the read-only groups: health, mounts, policies, auth methods and identities; no secret.
# Generated by tools/config/render/render_admin_sso.py; edit the generator, not this file.
path "sys/health" {
  capabilities = ["read"]
}
path "sys/seal-status" {
  capabilities = ["read"]
}
path "sys/mounts" {
  capabilities = ["read"]
}
path "sys/auth" {
  capabilities = ["read"]
}
path "sys/audit" {
  capabilities = ["read", "sudo"]
}
path "sys/policies/acl" {
  capabilities = ["list"]
}
path "sys/policies/acl/*" {
  capabilities = ["read"]
}
path "identity/group/*" {
  capabilities = ["read", "list"]
}
path "secret/*" {
  capabilities = ["deny"]
}
"""

SCRIPT = r"""#!/usr/bin/env bash
# Generated by tools/config/render/render_admin_sso.py from config/platform.yaml; edit the generator, not this file.
#
# Signs the people of the Okta groups in to one Vault through the OIDC auth method. Run it by hand as an operator, once per Vault
# (Vault runs per environment and region, Okta has one redirect host: the browser reaches the Vault the host name points to).
# The client secret is read from AWS Secrets Manager and goes from the pipe into Vault; it is never written to disk or printed,
# and no workload holds it.
#
# Needs: vault, aws, jq; VAULT_TOKEN of an operator in the environment; AWS credentials that read the secret.
# Safe to repeat: every step checks the current state first. --dry-run reads, prints the writes and changes nothing.
set -euo pipefail

SECRET_ID="@@SECRET_ID@@"
REDIRECTS='@@REDIRECTS@@'
GROUPS_TO_POLICY=(@@GROUP_POLICIES@@)
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
vault_addr=""
region="${AWS_REGION:-}"
dry_run=0

usage() {
  cat <<'EOF'
Usage: configure-oidc.sh --vault-addr URL [--region REGION] [--secret-id ID] [--dry-run]
  --vault-addr  address of the Vault to configure, for example https://vault.<zone> (required)
  --region      AWS region of the secret (default: AWS_REGION)
  --secret-id   Secrets Manager secret with client_id, client_secret and issuer (default: the one of the Vault application)
  --dry-run     print the changes without making them
EOF
}

while [ $# -gt 0 ]; do
  case "$1" in
    --vault-addr) vault_addr="${2:?--vault-addr needs a value}"; shift 2 ;;
    --region) region="${2:?--region needs a value}"; shift 2 ;;
    --secret-id) SECRET_ID="${2:?--secret-id needs a value}"; shift 2 ;;
    --dry-run) dry_run=1; shift ;;
    -h | --help) usage; exit 0 ;;
    *) echo "configure-oidc: unknown argument: $1" >&2; usage >&2; exit 2 ;;
  esac
done

case "$vault_addr" in
  https://*) ;;
  *) echo "configure-oidc: --vault-addr must be an https:// address" >&2; exit 2 ;;
esac
: "${VAULT_TOKEN:?configure-oidc: set VAULT_TOKEN of an operator}"
export VAULT_ADDR="$vault_addr"

say() { echo "configure-oidc: $*"; }
# Runs a change, or only prints it in a dry run
apply() {
  if [ "$dry_run" -eq 1 ]; then
    say "would run: $*"
  else
    "$@"
  fi
}

if [ "$dry_run" -eq 1 ]; then say "target $VAULT_ADDR (dry run)"; else say "target $VAULT_ADDR"; fi
vault status >/dev/null

# 1. The auth method
if vault auth list -format=json | jq -e 'has("oidc/")' >/dev/null; then
  say "auth method oidc/ is enabled"
else
  apply vault auth enable -path=oidc oidc
fi
accessor="$(vault auth list -format=json | jq -r '."oidc/".accessor // "<accessor of oidc/>"')"

# 2. The policies of the files next to this script (writing the same text again changes nothing)
apply vault policy write pay-oidc-admin "$DIR/admin.hcl"
apply vault policy write pay-oidc-readonly "$DIR/readonly.hcl"

# 3. The client of Okta: the secret travels through the pipe only
if [ "$dry_run" -eq 1 ]; then
  say "would write auth/oidc/config from secret $SECRET_ID"
else
  aws ${region:+--region "$region"} secretsmanager get-secret-value --secret-id "$SECRET_ID" --query SecretString --output text |
    jq -c '{oidc_discovery_url: .issuer, oidc_client_id: .client_id, oidc_client_secret: .client_secret, default_role: "okta"}' |
    vault write auth/oidc/config - >/dev/null
  say "auth/oidc/config written"
fi

# 4. The role: tokens live one hour and cannot outlive it; policies come from the groups, not from the role
role_json="$(jq -nc --argjson uris "$REDIRECTS" '{
  role_type: "oidc", user_claim: "email", groups_claim: "groups", oidc_scopes: ["email", "groups"],
  allowed_redirect_uris: $uris, token_ttl: "1h", token_max_ttl: "1h", token_explicit_max_ttl: "1h"}')"
if [ "$dry_run" -eq 1 ]; then
  say "would write auth/oidc/role/okta: $role_json"
else
  echo "$role_json" | vault write auth/oidc/role/okta - >/dev/null
  say "auth/oidc/role/okta written"
fi

# 5. External identity groups named like the Okta groups, each with its policy
for entry in "${GROUPS_TO_POLICY[@]}"; do
  name="${entry%%=*}"
  policy="${entry#*=}"
  group_id="$(vault read -field=id "identity/group/name/$name" 2>/dev/null || true)"
  if [ -z "$group_id" ]; then
    if [ "$dry_run" -eq 1 ]; then
      apply vault write identity/group name="$name" type=external policies="$policy"
      group_id="<id of $name>"
    else
      group_id="$(vault write -field=id identity/group name="$name" type=external policies="$policy")"
    fi
  else
    apply vault write identity/group name="$name" type=external policies="$policy"
  fi
  alias_name=""
  case "$group_id" in
    "<"*) ;;
    *) alias_name="$(vault read -format=json "identity/group/id/$group_id" | jq -r '.data.alias.name // empty')" ;;
  esac
  if [ -z "$alias_name" ]; then
    apply vault write identity/group-alias name="$name" mount_accessor="$accessor" canonical_id="$group_id"
  else
    say "group $name already has its alias"
  fi
done
say "done"
"""


class Dumper(yaml.SafeDumper):
    """SafeDumper that writes multi-line strings as literal blocks."""


Dumper.add_representer(str, lambda d, v: d.represent_scalar("tag:yaml.org,2002:str", v, style="|" if "\n" in v else None))


def dump(data, header):
    return f"# {header}\n" + yaml.dump(data, Dumper=Dumper, sort_keys=False, width=1000)


def external_secret(name, namespace, key, mapping, labels=None):
    target = {"name": name, "creationPolicy": "Owner"}
    if labels:
        # The labels go to the Secret that the operator creates, not to the ExternalSecret
        target["template"] = {"metadata": {"labels": labels}}
    return {
        "apiVersion": "external-secrets.io/v1",
        "kind": "ExternalSecret",
        "metadata": {"name": name, "namespace": namespace},
        "spec": {
            "refreshInterval": "1h",
            "secretStoreRef": {"kind": "ClusterSecretStore", "name": "aws-secrets-manager"},
            "target": target,
            "data": [{"secretKey": k, "remoteRef": {"key": key, "property": p}} for k, p in mapping.items()],
        },
    }


def secret_name(cfg, tool):
    return f"{cfg['naming']['prefix']}/{CENTRAL_ENV}/{tool}/oidc"


def argocd_values(cfg):
    groups = cfg["access"]["grafana_groups"]
    zone = cfg["dns"]["admin_zone"]
    policy = "".join(f"g, {groups[key]}, {role}\n" for key, role in ARGOCD_ROLE.items())
    oidc = {
        "name": "Okta",
        "issuer": f"https://{cfg['access']['okta_domain']}",
        "clientID": "$argocd-oidc:client_id",
        "clientSecret": "$argocd-oidc:client_secret",
        "enablePKCEAuthentication": True,
        "requestedScopes": ["openid", "profile", "email", "groups"],
    }
    return {
        "configs": {
            "cm": {
                # Annotation tracking lets hook resources of the migrations chart coexist with Helm labels
                "application.resourceTrackingMethod": "annotation",
                "url": f"https://argocd.{zone}",
                # People sign in through Okta only; no local admin account
                "admin.enabled": "false",
                "oidc.config": yaml.dump(oidc, Dumper=yaml.SafeDumper, sort_keys=False, width=1000),
            },
            "rbac": {
                # Nobody gets a role by default: a group that is not listed (finance) can sign in and sees nothing
                "policy.default": "",
                "policy.csv": policy,
                "scopes": "[groups]",
            },
            "params": {
                # TLS ends at the load balancer in front of the UI
                "server.insecure": True,
            },
        },
        "controller": {"metrics": {"enabled": True}},
        "server": {"metrics": {"enabled": True}},
        "applicationSet": {"metrics": {"enabled": True}},
        "redis-ha": {"enabled": True},
        # The label makes Argo CD read $argocd-oidc:<key> references from this Secret
        "extraObjects": [external_secret(
            "argocd-oidc", "argocd", secret_name(cfg, "argocd"), {"client_id": "client_id", "client_secret": "client_secret"},
            labels={"app.kubernetes.io/part-of": "argocd"})],
    }


def vault_files(cfg):
    groups = cfg["access"]["grafana_groups"]
    zone = cfg["dns"]["admin_zone"]
    uris = [f"https://vault.{zone}/ui/vault/auth/oidc/oidc/callback", "http://localhost:8250/oidc/callback"]
    pairs = " ".join(f'"{groups[key]}=pay-oidc-{policy}"' for key, policy in VAULT_POLICY.items())
    script = (SCRIPT.replace("@@SECRET_ID@@", secret_name(cfg, "vault"))
              .replace("@@REDIRECTS@@", yaml.safe_dump(uris, default_flow_style=True, width=1000).strip().replace("'", '"'))
              .replace("@@GROUP_POLICIES@@", pairs))
    base = OUT / "vault" / "oidc"
    return {base / "admin.hcl": ADMIN_HCL, base / "readonly.hcl": READONLY_HCL, base / "configure-oidc.sh": script}


def sentry_files(cfg):
    head = "Generated by tools/config/render/render_admin_sso.py from config/platform.yaml; edit the source, not this file."
    es = external_secret("sentry-oidc", "sentry", secret_name(cfg, "sentry"),
                         {"client_id": "client_id", "client_secret": "client_secret", "issuer": "issuer"})
    es["metadata"]["annotations"] = {"argocd.argoproj.io/sync-wave": "-2"}

    def ref(key):
        return {"secretKeyRef": {"name": "sentry-oidc", "key": key}}

    # Read by the sentry-auth-oidc plugin (sentry.conf.py of the custom image); stock Sentry ignores them
    env = [{"name": "OIDC_CLIENT_ID", "valueFrom": ref("client_id")},
           {"name": "OIDC_CLIENT_SECRET", "valueFrom": ref("client_secret")},
           {"name": "OIDC_DOMAIN", "valueFrom": ref("issuer")},
           {"name": "OIDC_SCOPE", "value": "openid email profile groups"}]
    return {
        OUT / "sentry" / "manifests" / "externalsecret-oidc.yaml": dump(es, head),
        OUT / "sentry" / "oidc-values.yaml": dump({"sentry": {"web": {"env": env}}}, head),
    }


def render(cfg):
    head = "Generated by tools/config/render/render_admin_sso.py from config/platform.yaml; edit the source, not this file."
    files = {OUT / "argocd" / "values.yaml": dump(argocd_values(cfg), head)}
    files.update(vault_files(cfg))
    files.update(sentry_files(cfg))
    return files


def main(argv):
    check = "--check" in argv
    cfg = yaml.safe_load((ROOT / "config" / "platform.yaml").read_text(encoding="utf-8"))
    changed = []
    for path, text in render(cfg).items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            changed.append(path.relative_to(ROOT).as_posix())
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
        if not check and path.suffix == ".sh":
            path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    verb = "would change" if check else "updated"
    for c in changed:
        print(f"render-admin-sso: {verb} {c}")
    print(f"render-admin-sso: {len(changed)} file(s) {verb}")
    return 1 if changed and check else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
