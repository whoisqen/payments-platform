#!/usr/bin/env python3
"""Write the values of the central rule evaluator (vmalert) from the alert rules under observability/.

Usage: render_vmalert.py [--check]. Without --check the file is rewritten; with it the exit code is 1 when it would change.
The in-cluster Prometheus keeps 6 hours, so a rule that looks further back (offset 1d, a 3 day window) can never fire there. Those
rules (the SLO windows of 3 and 30 days, the alerts with offset 1d or 1w), and the ones that read a metric only the central store has,
are evaluated by vmalert against the central store instead; the SLO recordings are written back to it.
The notifier address and the external labels (runbook and Grafana links) come from the add-on parameters.
"""
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "deploy" / "platform" / "vmalert" / "values.yaml"
ALERTS = ROOT / "observability" / "alerts"
# Written by observability/slo/generate.py: the 3 and 30 day windows and everything built on them
SLO_CENTRAL = ROOT / "observability" / "slo" / "generated" / "central"
LOCAL_RETENTION_S = 6 * 3600
# Alerts that read a metric the collector sends only to the central store
CENTRAL_ONLY = {"PanDetectedInLogs"}
UNIT = {"s": 1, "m": 60, "h": 3600, "d": 86400, "w": 7 * 86400}
SELECT = "http://vm-victoria-metrics-cluster-vmselect.victoria-metrics.svc:8481/select/0/prometheus"
INSERT = "http://vm-victoria-metrics-cluster-vminsert.victoria-metrics.svc:8480/insert/0/prometheus"


def seconds(match):
    return int(match.group(1)) * UNIT[match.group(2)]


def lookback(expr):
    """Longest window or offset of an expression, in seconds."""
    windows = [seconds(m) for m in re.finditer(r"\[(\d+)([smhdw])(?::\d+[smhdw])?\]", expr)]
    offsets = [seconds(m) for m in re.finditer(r"offset (\d+)([smhdw])", expr)]
    return max(windows + offsets + [0])


def central_rules():
    groups = []
    for root, everything in ((ALERTS, False), (SLO_CENTRAL, True)):
        for path in sorted(root.rglob("*.yaml")):
            doc = yaml.safe_load(path.read_text(encoding="utf-8"))
            for group in doc["spec"]["groups"]:
                rules = [r for r in group["rules"] if everything or (r.get("alert") in CENTRAL_ONLY or ("alert" in r and lookback(r["expr"]) > LOCAL_RETENTION_S))]
                if rules:
                    groups.append({"name": f"central-{group['name']}", "interval": "1m", "rules": rules})
    return groups


def render():
    values = {"server": {
        "replicaCount": 2,
        "datasource": {"url": SELECT},
        # The recorded 3 and 30 day ratios are written back, where the dashboards and the burn alerts read them
        "remoteWrite": {"url": INSERT + "/api/v1/write"},
        # vmalert does not repeat a notification; both replicas send the same alert and the Alertmanager cluster merges them
        "extraArgs": {"rule": ["/config/alert-rules.yaml"], "envflag.enable": True, "envflag.prefix": "VM_", "loggerFormat": "json"},
        "podDisruptionBudget": {"enabled": True, "minAvailable": 1},
        "affinity": {"podAntiAffinity": {"requiredDuringSchedulingIgnoredDuringExecution": [
            {"topologyKey": "kubernetes.io/hostname", "labelSelector": {"matchLabels": {"app": "server"}}}]}},
        "config": {"alerts": {"groups": central_rules()}},
    }, "alertmanager": {"enabled": False}}
    head = "# Generated by tools/config/render/render_vmalert.py from observability/alerts and observability/slo; edit the rules, not this file.\n"
    return head + yaml.dump(values, Dumper=yaml.SafeDumper, sort_keys=False, width=1000)


def main(argv):
    text = render()
    changed = not OUT.exists() or OUT.read_text(encoding="utf-8") != text
    if changed and "--check" not in argv:
        OUT.parent.mkdir(parents=True, exist_ok=True)
        OUT.write_text(text, encoding="utf-8")
    verb = "would change" if "--check" in argv else "updated"
    print(f"render-vmalert: {int(changed)} file(s) {verb}")
    return 1 if changed and "--check" in argv else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
