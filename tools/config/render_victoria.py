#!/usr/bin/env python3
"""Write the storage class and the backup jobs of the central metrics store from config/platform.yaml.

Usage: render_victoria.py [--check]. Without --check the files are rewritten; with it the exit code is 1 when any file would change.
deploy/platform/victoria-metrics/manifests/storageclass.yaml: encrypted gp3 volumes for vmstorage, kept when a claim is deleted.
deploy/platform/victoria-metrics/manifests/vmbackup.yaml: one CronJob per vmstorage pod. A job runs on the node of its pod (the volume is
ReadWriteOnce), asks vmstorage for a snapshot and copies it incrementally to S3; the snapshot is deleted afterwards.
"""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "deploy" / "platform" / "victoria-metrics" / "manifests"
NAMESPACE = "victoria-metrics"
CENTRAL_ENV = "shared-services"
RELEASE = "vm"  # the release name that the add-on sets
FULLNAME = f"{RELEASE}-victoria-metrics-cluster"
REPLICAS = 3
IMAGE = "victoriametrics/vmbackup:v1.157.0@sha256:49b0967aeb8c9497be3da4b5940c9b2e8e1e20005d097f16a44ccba4fb1dcb40"
STORAGE_CLASS = "gp3-encrypted"
SCHEDULE_MINUTES = (7, 17, 27)  # staggered, so that the three nodes do not copy at once


def region_short(region):
    area, direction, number = region.split("-")
    return f"{area}{direction[0]}{number}"


def dump(documents, header):
    text = "".join("---\n" + yaml.dump(d, Dumper=yaml.SafeDumper, sort_keys=False, width=1000) for d in documents)
    return f"# {header}\n" + text


def render(cfg):
    prefix, region = cfg["naming"]["prefix"], cfg["regions"]["working"]
    account = cfg["accounts"]["shared_services"]
    short = region_short(region)
    bucket = f"{prefix}-{CENTRAL_ENV}-{short}-vmbackup"
    key_alias = f"arn:aws:kms:{region}:{account}:alias/{prefix}-{CENTRAL_ENV}-{short}-shared"
    head = "Generated by tools/config/render_victoria.py from config/platform.yaml; edit the generator, not this file."
    storage_class = {
        "apiVersion": "storage.k8s.io/v1", "kind": "StorageClass", "metadata": {"name": STORAGE_CLASS},
        "provisioner": "ebs.csi.aws.com",
        "parameters": {"type": "gp3", "encrypted": "true", "kmsKeyId": key_alias, "fsType": "ext4"},
        # The metrics history outlives a deleted claim; the volume is removed by hand
        "reclaimPolicy": "Retain", "allowVolumeExpansion": True, "volumeBindingMode": "WaitForFirstConsumer",
    }
    documents = [{"apiVersion": "v1", "kind": "ServiceAccount", "metadata": {"name": "vmbackup", "namespace": NAMESPACE},
                  "automountServiceAccountToken": False}]
    for i in range(REPLICAS):
        pod = f"{FULLNAME}-vmstorage-{i}"
        labels = {"app.kubernetes.io/name": "vmbackup", "app.kubernetes.io/instance": f"vmbackup-{i}"}
        documents.append({
            "apiVersion": "batch/v1", "kind": "CronJob",
            "metadata": {"name": f"vmbackup-{i}", "namespace": NAMESPACE, "labels": labels},
            "spec": {
                "schedule": f"{SCHEDULE_MINUTES[i % len(SCHEDULE_MINUTES)]} * * * *",
                "concurrencyPolicy": "Forbid", "successfulJobsHistoryLimit": 1, "failedJobsHistoryLimit": 3,
                "jobTemplate": {"spec": {
                    "backoffLimit": 1, "activeDeadlineSeconds": 3000,
                    "template": {"metadata": {"labels": labels}, "spec": {
                        "serviceAccountName": "vmbackup", "restartPolicy": "Never", "automountServiceAccountToken": False,
                        # The volume is ReadWriteOnce: the job must run on the node of the pod that holds it
                        "affinity": {"podAffinity": {"requiredDuringSchedulingIgnoredDuringExecution": [{
                            "topologyKey": "kubernetes.io/hostname",
                            "namespaces": [NAMESPACE],
                            "labelSelector": {"matchLabels": {"statefulset.kubernetes.io/pod-name": pod}}}]}},
                        "securityContext": {"runAsNonRoot": True, "runAsUser": 65534, "runAsGroup": 65534, "seccompProfile": {"type": "RuntimeDefault"}},
                        "containers": [{
                            "name": "vmbackup", "image": IMAGE,
                            "args": ["-storageDataPath=/storage", f"-snapshot.createURL=http://{pod}.{FULLNAME}-vmstorage.{NAMESPACE}.svc:8482/snapshot/create",
                                     f"-dst=s3://{bucket}/vmstorage-{i}", "-loggerFormat=json"],
                            "env": [{"name": "AWS_REGION", "value": region}],
                            "securityContext": {"allowPrivilegeEscalation": False, "readOnlyRootFilesystem": True, "capabilities": {"drop": ["ALL"]}},
                            "resources": {"requests": {"cpu": "100m", "memory": "256Mi"}, "limits": {"memory": "512Mi"}},
                            "volumeMounts": [{"name": "storage", "mountPath": "/storage", "readOnly": True}]}],
                        "volumes": [{"name": "storage", "persistentVolumeClaim": {"claimName": f"vmstorage-volume-{pod}", "readOnly": True}}]}}}},
            }})
    documents.append({
        "apiVersion": "networking.k8s.io/v1", "kind": "NetworkPolicy", "metadata": {"name": "vmbackup", "namespace": NAMESPACE},
        "spec": {"podSelector": {"matchLabels": {"app.kubernetes.io/name": "vmbackup"}}, "policyTypes": ["Ingress", "Egress"],
                 "egress": [
                     {"to": [{"podSelector": {"matchLabels": {"app": "vmstorage"}}}], "ports": [{"protocol": "TCP", "port": 8482}]},
                     {"to": [{"namespaceSelector": {"matchLabels": {"kubernetes.io/metadata.name": "kube-system"}}}],
                      "ports": [{"protocol": "UDP", "port": 53}, {"protocol": "TCP", "port": 53}]},
                     # S3 and the Pod Identity agent
                     {"ports": [{"protocol": "TCP", "port": 443}, {"protocol": "TCP", "port": 80}]}]}})
    return {OUT / "storageclass.yaml": dump([storage_class], head), OUT / "vmbackup.yaml": dump(documents, head)}


def main(argv):
    cfg = yaml.safe_load((ROOT / "config" / "platform.yaml").read_text(encoding="utf-8"))
    changed = []
    for path, text in render(cfg).items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            changed.append(path.relative_to(ROOT).as_posix())
            if "--check" not in argv:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    verb = "would change" if "--check" in argv else "updated"
    for c in changed:
        print(f"render-victoria: {verb} {c}")
    print(f"render-victoria: {len(changed)} file(s) {verb}")
    return 1 if changed and "--check" in argv else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
