#!/usr/bin/env python3
"""Write the values of the OpenTelemetry collector add-on from observability/otel/collector.yaml, the config that is tested.

Usage: render_otel.py [--check]. Without --check the file is rewritten; with it the exit code is 1 when it would change.
The collector runs on every node and receives OTLP without TLS on that node only (Service with internalTrafficPolicy Local and a
NetworkPolicy), because the Hyperswitch OTLP client has no client certificate; the receiver TLS of the tested file is dropped here.
Everything that leaves the cluster keeps the mutual TLS of the tested file, with the certificate from the Secret otel-collector-tls.
"""
import copy
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "observability" / "otel" / "collector.yaml"
OUT = ROOT / "deploy" / "platform" / "otel-collector" / "values.yaml"
CONTRIB = "ghcr.io/open-telemetry/opentelemetry-collector-releases/opentelemetry-collector-contrib"
# receivers and pipeline of the chart defaults that the tested config does not use
DEFAULT_RECEIVERS = ["jaeger", "zipkin", "prometheus"]
UNUSED_PORTS = ["jaeger-compact", "jaeger-thrift", "jaeger-grpc", "zipkin"]


def render():
    config = copy.deepcopy(yaml.safe_load(SRC.read_text(encoding="utf-8")))
    for proto in config["receivers"]["otlp"]["protocols"].values():
        proto.pop("tls", None)
    for name in DEFAULT_RECEIVERS:
        config["receivers"][name] = None
    config["exporters"]["debug"] = None
    # the chart default pipeline `logs` would send every log record unmasked to the debug exporter
    config["service"]["pipelines"]["logs"] = None
    values = {
        "mode": "daemonset",
        # the Service the applications address: otel-collector.monitoring.svc.cluster.local
        "fullnameOverride": "otel-collector",
        "image": {"repository": CONTRIB},
        "command": {"name": "otelcol-contrib"},
        "presets": {},
        "ports": {name: {"enabled": False} for name in UNUSED_PORTS},
        "service": {"enabled": True, "internalTrafficPolicy": "Local"},
        "extraVolumes": [{"name": "tls", "secret": {"secretName": "otel-collector-tls"}}],
        "extraVolumeMounts": [{"name": "tls", "mountPath": "/etc/otel/tls", "readOnly": True}],
        "config": config,
    }
    header = ("# Generated by tools/config/render_otel.py from observability/otel/collector.yaml; edit that file, not this one.\n"
              "# The environment variables PLATFORM_ENV, PLATFORM_REGION and CENTRAL_* come from the add-on parameters.\n")
    return header + yaml.dump(values, Dumper=yaml.SafeDumper, sort_keys=False, width=1000)


def main(argv):
    text = render()
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else None
    changed = current != text
    if changed and "--check" not in argv:
        OUT.write_text(text, encoding="utf-8")
    verb = "would change" if "--check" in argv else "updated"
    print(f"render-otel: {1 if changed else 0} file(s) {verb}")
    return 1 if changed and "--check" in argv else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
