#!/usr/bin/env python3
"""Write the deploy files of the central Alertmanager from observability/alertmanager (config as code) and config/platform.yaml.

Usage: render_central.py [--check]. Without --check the files are rewritten; with it the exit code is 1 when any file would change.
Files: deploy/platform/alertmanager/values.yaml (chart values: three replicas, the config and the templates) and
deploy/platform/alertmanager/manifests/externalsecret.yaml (the Slack webhook files that the config reads, from Secrets Manager).
"""
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "observability" / "alertmanager"
OUT = ROOT / "deploy" / "platform" / "alertmanager"
SECRET_DIR = "/etc/alertmanager/secrets/"
CENTRAL_ENV = "shared-services"


class Literal(str):
    pass


def literal_representer(dumper, data):
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")


yaml.add_representer(Literal, literal_representer, Dumper=yaml.SafeDumper)


def secret_files(config):
    """Names of the files under /etc/alertmanager/secrets that the receivers read."""
    return sorted(set(re.findall(re.escape(SECRET_DIR) + r"([\w.-]+)", yaml.safe_dump(config))))


def render(cfg):
    prefix = cfg["naming"]["prefix"]
    config = yaml.safe_load((SRC / "alertmanager.yaml").read_text(encoding="utf-8"))
    config["templates"] = ["/etc/alertmanager/*.tmpl"]
    templates = {p.name: Literal(p.read_text(encoding="utf-8")) for p in sorted((SRC / "templates").glob("*.tmpl"))}
    values = {
        "# generated": None,
        "replicaCount": 3,
        # Three nodes gossip silences and notifications, so a failed one loses nothing and a pair of replicas of Prometheus is not paged twice
        "podAntiAffinity": "hard",
        "podAntiAffinityTopologyKey": "kubernetes.io/hostname",
        "topologySpreadConstraints": [{
            "maxSkew": 1, "topologyKey": "topology.kubernetes.io/zone", "whenUnsatisfiable": "ScheduleAnyway",
            "labelSelector": {"matchLabels": {"app.kubernetes.io/name": "alertmanager"}}}],
        "podDisruptionBudget": {"minAvailable": 2},
        "persistence": {"enabled": True, "size": "2Gi"},
        "extraSecretMounts": [{"name": "secrets", "mountPath": SECRET_DIR.rstrip("/"), "secretName": "alertmanager-secrets", "readOnly": True}],
        "config": {"enabled": True, **config},
        "templates": templates,
    }
    del values["# generated"]
    header = "# Generated by tools/config/render_central.py from observability/alertmanager; edit the sources, not this file.\n"
    values_text = header + yaml.dump(values, Dumper=yaml.SafeDumper, sort_keys=False, width=1000)
    external = {
        "apiVersion": "external-secrets.io/v1",
        "kind": "ExternalSecret",
        "metadata": {"name": "alertmanager-secrets", "namespace": "monitoring"},
        "spec": {
            "refreshInterval": "1h",
            "secretStoreRef": {"kind": "ClusterSecretStore", "name": "aws-secrets-manager"},
            "target": {"name": "alertmanager-secrets", "creationPolicy": "Owner"},
            "data": [{"secretKey": name, "remoteRef": {"key": f"{prefix}/{CENTRAL_ENV}/alertmanager/{name}"}} for name in secret_files(config)],
        },
    }
    external_text = ("# Generated by tools/config/render_central.py: the files the Alertmanager receivers read, from AWS Secrets Manager.\n"
                     + yaml.dump(external, Dumper=yaml.SafeDumper, sort_keys=False))
    return {OUT / "values.yaml": values_text, OUT / "manifests" / "externalsecret.yaml": external_text}


def main(argv):
    cfg = yaml.safe_load((ROOT / "config" / "platform.yaml").read_text(encoding="utf-8"))
    changed = []
    for path, text in render(cfg).items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            changed.append(path.relative_to(ROOT).as_posix())
            if "--check" not in argv:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    verb = "would change" if "--check" in argv else "updated"
    for c in changed:
        print(f"render-central: {verb} {c}")
    print(f"render-central: {len(changed)} file(s) {verb}")
    return 1 if changed and "--check" in argv else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
