#!/usr/bin/env python3
"""Write deploy/platform/sentry/manifests/externalsecret.yaml: the Secret `sentry-secrets` from AWS Secrets Manager.

Usage: render_sentry.py [--check]. Secrets Manager names are <naming.prefix>/shared-services/sentry/<name>; no value is in git.
"""
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "deploy" / "platform" / "sentry" / "manifests" / "externalsecret.yaml"
CENTRAL_ENV = "shared-services"
# Kubernetes Secret key -> Secrets Manager name under sentry/
KEYS = {
    "system-secret-key": "system-secret-key",
    "admin-password": "admin-password",
    "postgres-password": "postgres-password",
    "replication-password": "postgres-replication-password",
    "redis-password": "redis-password",
    "clickhouse-password": "clickhouse-password",
    "launchpad-rpc-secret": "launchpad-rpc-secret",
}


def render(cfg):
    prefix = cfg["naming"]["prefix"]
    external = {
        "apiVersion": "external-secrets.io/v1",
        "kind": "ExternalSecret",
        "metadata": {"name": "sentry-secrets", "namespace": "sentry", "annotations": {"argocd.argoproj.io/sync-wave": "-2"}},
        "spec": {
            "refreshInterval": "1h",
            "secretStoreRef": {"kind": "ClusterSecretStore", "name": "aws-secrets-manager"},
            "target": {"name": "sentry-secrets", "creationPolicy": "Owner"},
            "data": [{"secretKey": key, "remoteRef": {"key": f"{prefix}/{CENTRAL_ENV}/sentry/{name}"}} for key, name in KEYS.items()],
        },
    }
    text = ("# Generated by tools/config/render_sentry.py: the credentials of Sentry and its databases, from AWS Secrets Manager.\n"
            + yaml.dump(external, Dumper=yaml.SafeDumper, sort_keys=False))
    return {OUT: text}


def main(argv):
    cfg = yaml.safe_load((ROOT / "config" / "platform.yaml").read_text(encoding="utf-8"))
    changed = []
    for path, text in render(cfg).items():
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            changed.append(path.relative_to(ROOT).as_posix())
            if "--check" not in argv:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    verb = "would change" if "--check" in argv else "updated"
    for c in changed:
        print(f"render-sentry: {verb} {c}")
    print(f"render-sentry: {len(changed)} file(s) {verb}")
    return 1 if changed and "--check" in argv else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
