#!/usr/bin/env python3
"""Write the manifests that deploy the metric exporters of observability/exporters, from those files and config/platform.yaml.

Files under deploy/platform/exporters/<exporter>/:
  common/monitors.yaml                  ServiceMonitor, PodMonitor and Probe documents of observability/exporters/<exporter>.yaml
  common/networkpolicy.yaml             exporters without a per-environment data store (blackbox)
  envs/<env>/<region>/externalsecret.yaml  connection secret from Secrets Manager <prefix>/<env>/exporters/<exporter>
  envs/<env>/<region>/networkpolicy.yaml   default deny, one egress to the data store CIDRs, ingress from the monitoring namespace

Usage: render_exporters.py [--check]. Without --check the files are rewritten; with it the exit code is 1 when any file would change.
"""
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import render_vault  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "observability" / "exporters"
OUT = ROOT / "deploy" / "platform" / "exporters"
NAMESPACE = "monitoring"
MONITOR_KINDS = ("ServiceMonitor", "PodMonitor", "Probe")
# Secret keys and their properties inside the one Secrets Manager secret of the exporter
SECRETS = {
    "postgres": {"name": "postgres-exporter-dsn", "keys": ["dsn"]},
    "redis": {"name": "memorydb-exporter-auth", "keys": ["password", "address"]},
    "kafka": {"name": "msk-exporter-tls", "keys": ["ca.crt", "tls.crt", "tls.key"]},
}
# Pod port that Prometheus scrapes and the data store port the exporter connects to
PORTS = {"postgres": (9187, 5432), "redis": (9121, 6379), "kafka": (9308, 9094), "blackbox": (9115, None)}
# The chart names the kafka-exporter service port exporter-port, not the name written in the source
PORT_FIXES = {"kafka": {"kafka-exporter": "exporter-port"}}


def header(what):
    return f"# Generated by tools/config/render_exporters.py: {what}; edit the sources, not this file.\n"


def dump(docs):
    return "---\n".join(yaml.dump(d, Dumper=yaml.SafeDumper, sort_keys=False, width=1000) for d in docs)


def monitors(name):
    docs = [d for d in yaml.safe_load_all((SRC / f"{name}.yaml").read_text(encoding="utf-8")) if d and d.get("kind") in MONITOR_KINDS]
    for doc in docs:
        for ep in doc["spec"].get("endpoints", []):
            ep["port"] = PORT_FIXES.get(name, {}).get(ep["port"], ep["port"])
    return docs


def policy(name, data_cidrs):
    scrape, store = PORTS[name]
    dns = {"to": [{"namespaceSelector": {"matchLabels": {"kubernetes.io/metadata.name": "kube-system"}},
                   "podSelector": {"matchLabels": {"k8s-app": "kube-dns"}}}],
           "ports": [{"protocol": "UDP", "port": 53}, {"protocol": "TCP", "port": 53}]}
    if store:
        data = {"to": [{"ipBlock": {"cidr": c}} for c in data_cidrs], "ports": [{"protocol": "TCP", "port": store}]}
    else:
        data = {"to": [{"ipBlock": {"cidr": "0.0.0.0/0"}}], "ports": [{"protocol": "TCP", "port": 443}]}
    return {
        "apiVersion": "networking.k8s.io/v1",
        "kind": "NetworkPolicy",
        "metadata": {"name": f"{name}-exporter", "namespace": NAMESPACE, "labels": {"app.kubernetes.io/part-of": "payments-platform"}},
        "spec": {
            "podSelector": {"matchLabels": {"app.kubernetes.io/name": f"prometheus-{name}-exporter"}},
            "policyTypes": ["Ingress", "Egress"],
            "ingress": [{"from": [{"namespaceSelector": {"matchLabels": {"kubernetes.io/metadata.name": NAMESPACE}}}],
                         "ports": [{"protocol": "TCP", "port": scrape}]}],
            "egress": [dns, data],
        },
    }


def external_secret(prefix, env, name):
    s = SECRETS[name]
    key = f"{prefix}/{env}/exporters/{name}"
    return {
        "apiVersion": "external-secrets.io/v1",
        "kind": "ExternalSecret",
        "metadata": {"name": s["name"], "namespace": NAMESPACE},
        "spec": {
            "refreshInterval": "1h",
            "secretStoreRef": {"kind": "ClusterSecretStore", "name": "aws-secrets-manager"},
            "target": {"name": s["name"], "creationPolicy": "Owner"},
            "data": [{"secretKey": k, "remoteRef": {"key": key, "property": k}} for k in s["keys"]],
        },
    }


def data_cidrs(cfg, env, region):
    d = cfg["deploy"][env]
    return d["data_cidrs"] if region == cfg["regions"]["working"] else d["standby"][region]["data_cidrs"]


def render(cfg):
    prefix = cfg["naming"]["prefix"]
    files = {}
    for name in ("postgres", "redis", "kafka", "clickhouse", "blackbox"):
        files[OUT / name / "common" / "monitors.yaml"] = header(f"monitors of observability/exporters/{name}.yaml") + dump(monitors(name))
    files[OUT / "blackbox" / "common" / "networkpolicy.yaml"] = header("blackbox-exporter: DNS and HTTPS probes only") + dump([policy("blackbox", [])])
    for env, regions in render_vault.environments(cfg).items():
        for region in regions:
            for name in SECRETS:
                base = OUT / name / "envs" / env / region
                files[base / "externalsecret.yaml"] = header(f"{name} exporter connection secret from AWS Secrets Manager") + dump([external_secret(prefix, env, name)])
                files[base / "networkpolicy.yaml"] = header(f"{name} exporter default deny, egress to the data subnets of {env} {region}") + dump([policy(name, data_cidrs(cfg, env, region))])
    return files


def main(argv):
    cfg = yaml.safe_load((ROOT / "config" / "platform.yaml").read_text(encoding="utf-8"))
    check = "--check" in argv
    changed = []
    for path, text in render(cfg).items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != text:
            changed.append(path.relative_to(ROOT).as_posix())
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    verb = "would change" if check else "updated"
    for c in changed:
        print(f"render-exporters: {verb} {c}")
    print(f"render-exporters: {len(changed)} file(s) {verb}")
    return 1 if changed and check else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
