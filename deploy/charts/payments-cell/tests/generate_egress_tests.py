#!/usr/bin/env python3
"""Write one helm-unittest suite per cell directory under deploy/envs: every external host of the merged layers has a ServiceEntry.

Usage: generate_egress_tests.py [--check]. With --check the exit code is 1 when a suite is missing or out of date.
"""
import os
import sys
from pathlib import Path

import yaml

CHART = Path(__file__).resolve().parents[1]
ENVS = CHART.parents[1] / "envs"


def merge(a, b):
    out = dict(a)
    for k, v in (b or {}).items():
        out[k] = merge(out[k], v) if isinstance(v, dict) and isinstance(out.get(k), dict) else v
    return out


def layers(env, region, cell):
    files = [ENVS / env / "values.yaml", ENVS / env / region / "values.yaml", ENVS / env / region / cell / "values.yaml"]
    return [f for f in files if f.is_file()]


def selector(name):
    return {"path": "metadata.name", "value": name}


def suite(env, region, cell):
    files = layers(env, region, cell)
    vals = {}
    for f in files:
        vals = merge(vals, yaml.safe_load(f.read_text(encoding="utf-8")))
    g = vals.get("global", {})
    hs = g.get("hyperswitch", {})
    egress = g.get("egress", {})
    tests = []
    db = hs.get("database", {}).get("host")
    if db:
        tests.append({"it": "registers the Aurora proxy", "documentSelector": selector("egress-aurora"),
                      "asserts": [{"contains": {"path": "spec.hosts", "content": db}}]})
    redis = hs.get("redis", {}).get("host")
    if redis:
        tests.append({"it": "registers the MemoryDB endpoint", "documentSelector": selector("egress-memorydb"),
                      "asserts": [{"contains": {"path": "spec.hosts", "content": redis}}]})
    events = hs.get("events", {})
    if events.get("kafka"):
        hosts = [b.rsplit(":", 1)[0] for b in events.get("brokers", [])]
        tests.append({"it": "registers every MSK broker", "documentSelector": selector("egress-msk"),
                      "asserts": [{"contains": {"path": "spec.hosts", "content": h}} for h in hosts]})
    for key, name in (("pspHosts", "egress-psp"), ("sentryHosts", "egress-sentry")):
        hosts = egress.get(key) or []
        if hosts:
            tests.append({"it": f"registers {key}", "documentSelector": selector(name),
                          "asserts": [{"contains": {"path": "spec.hosts", "content": h}} for h in hosts]})
    here = CHART / "tests" / f"egress-{env}"
    rel = [os.path.relpath(f, here) for f in files]
    doc = {"suite": f"{env}/{region}/{cell}: every external host has a ServiceEntry (generated by generate_egress_tests.py)",
           "templates": ["serviceentries.yaml"],
           "values": ["../../ci/lint-values.yaml"] + rel,
           "tests": tests}
    return "# Generated by tests/generate_egress_tests.py from deploy/envs; edit the layers, not this file.\n" + yaml.safe_dump(doc, sort_keys=False)


def targets():
    out = {}
    for cell_dir in sorted(ENVS.glob("*/*/*")):
        if not cell_dir.is_dir() or not (cell_dir.name.startswith("cell-") or cell_dir.name == "spare"):
            continue
        env, region, cell = cell_dir.parts[-3:]
        out[CHART / "tests" / f"egress-{env}" / f"{region}-{cell}_test.yaml"] = suite(env, region, cell)
    return out


def main(argv):
    check = "--check" in argv
    want = targets()
    stale = [p for p, text in want.items() if not p.is_file() or p.read_text(encoding="utf-8") != text]
    extra = [p for p in CHART.glob("tests/egress-*/*_test.yaml") if p not in want]
    if check:
        for p in stale + extra:
            print(f"generate-egress-tests: {p.relative_to(CHART)} is out of date")
        return 1 if stale or extra else 0
    for p in extra:
        p.unlink()
    for p, text in want.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    print(f"generate-egress-tests: {len(want)} suite(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
